"""Small, explicit SQLite-to-PostgreSQL migration translations.

This module is intentionally limited to syntax present in SignalForce's checked-in
SQLite migrations. Runtime query adaptation is handled separately; do not treat this
as a general SQL transpiler.
"""
import re


_AUTOINCREMENT = re.compile(
    r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.IGNORECASE
)
_IGNORE_INSERT = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\b", re.IGNORECASE)
_NOCASE = re.compile(r"\s+COLLATE\s+NOCASE\b", re.IGNORECASE)
_NOW_STRFTIME = re.compile(
    r"strftime\(\s*'%Y-%m-%dT%H:%M:%SZ'\s*,\s*'now'\s*\)",
    re.IGNORECASE,
)


def translate_migration_sql(sql: str, migration_name: str = "") -> str:
    """Translate the SQLite constructs used by existing migrations to PostgreSQL."""
    translated = _AUTOINCREMENT.sub(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql
    )
    timestamp_text = (
        """to_char(timezone('utc', CURRENT_TIMESTAMP), 'YYYY-MM-DD"T"HH24:MI:SS"Z"')"""
    )
    translated = _NOW_STRFTIME.sub(timestamp_text, translated)
    # SQLite stores CURRENT_TIMESTAMP as text; PostgreSQL's value is a timestamp.
    translated = re.sub(
        r"\bupdated_at\s*=\s*CURRENT_TIMESTAMP\b",
        "updated_at=" + timestamp_text,
        translated,
        flags=re.IGNORECASE,
    )

    # PostgreSQL has no column-level NOCASE collation. Customer emails are
    # normalized by the application; this expression index preserves the DB
    # uniqueness guarantee even if a writer bypasses that normalization.
    has_nocase = bool(_NOCASE.search(translated))
    translated = _NOCASE.sub("", translated)

    # Apply ON CONFLICT only to the specific INSERT OR IGNORE statement, not
    # to other INSERT statements in the same migration.
    pieces = re.split(r"(;)", translated)
    for index in range(0, len(pieces), 2):
        statement = pieces[index]
        if _IGNORE_INSERT.search(statement):
            statement = _IGNORE_INSERT.sub("INSERT INTO", statement, count=1)
            if "ON CONFLICT" not in statement.upper():
                statement = statement.rstrip() + " ON CONFLICT DO NOTHING"
            pieces[index] = statement

    translated = "".join(pieces)
    if has_nocase and migration_name == "013_customer_identity_foundation.sql":
        translated += (
            "\nCREATE UNIQUE INDEX IF NOT EXISTS idx_customer_accounts_email_lower "
            "ON customer_accounts (LOWER(email));\n"
        )
    return translated
