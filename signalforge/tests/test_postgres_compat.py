from app.postgres_compat import translate_migration_sql
from app.db import HybridRow, _postgres_runtime_sql, _qmark_to_pyformat


def test_translates_autoincrement_primary_keys():
    sql = "CREATE TABLE events (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);"
    result = translate_migration_sql(sql)
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in result
    assert "AUTOINCREMENT" not in result


def test_translates_insert_or_ignore_without_changing_other_inserts():
    sql = (
        "INSERT OR IGNORE INTO flags(id) VALUES(1);"
        "INSERT INTO events(name) VALUES('created');"
    )
    result = translate_migration_sql(sql)
    assert "INSERT INTO flags(id) VALUES(1) ON CONFLICT DO NOTHING;" in result
    assert "INSERT INTO events(name) VALUES('created');" in result


def test_translates_sqlite_utc_strftime_expression():
    sql = "INSERT INTO flags(changed_at) VALUES(strftime('%Y-%m-%dT%H:%M:%SZ','now'));"
    result = translate_migration_sql(sql)
    assert "to_char(timezone('utc', CURRENT_TIMESTAMP)" in result
    assert "strftime(" not in result


def test_replaces_nocase_with_case_insensitive_unique_index():
    sql = "CREATE TABLE customer_accounts (email TEXT NOT NULL COLLATE NOCASE UNIQUE);"
    result = translate_migration_sql(sql, "013_customer_identity_foundation.sql")
    assert "COLLATE NOCASE" not in result
    assert "LOWER(email)" in result
    assert "idx_customer_accounts_email_lower" in result


def test_does_not_add_email_index_to_unrelated_migrations():
    sql = "CREATE TABLE sample (name TEXT COLLATE NOCASE);"
    result = translate_migration_sql(sql, "001_init.sql")
    assert "LOWER(email)" not in result



def test_qmark_parameter_translation_preserves_question_marks_in_literals():
    sql = "SELECT * FROM events WHERE label='why?' AND id=? AND note=\"what?\""
    assert _qmark_to_pyformat(sql) == "SELECT * FROM events WHERE label='why?' AND id=%s AND note=\"what?\""


def test_postgres_paper_bot_claim_uses_row_lock():
    sql = "SELECT lock_owner,lock_until_epoch FROM paper_bot_state WHERE id=1"
    assert _postgres_runtime_sql(sql).endswith("FOR UPDATE")


def test_postgres_runtime_translates_immediate_begin():
    assert _postgres_runtime_sql("BEGIN IMMEDIATE") == "BEGIN"


def test_hybrid_row_supports_mapping_and_sqlite_integer_indexes():
    row = HybridRow(["id", "email"], [7, "trader@example.test"])
    assert row["email"] == "trader@example.test"
    assert row[0] == 7
    assert dict(row) == {"id": 7, "email": "trader@example.test"}



def test_all_checked_in_migrations_translate_known_sqlite_syntax():
    from pathlib import Path

    migrations = Path(__file__).parents[1] / "app" / "migrations"
    for migration in sorted(migrations.glob("*.sql")):
        translated = translate_migration_sql(migration.read_text(), migration.name)
        upper = translated.upper()
        assert "AUTOINCREMENT" not in upper, migration.name
        assert "INSERT OR IGNORE" not in upper, migration.name
        assert "COLLATE NOCASE" not in upper, migration.name
        assert "STRFTIME(" not in upper, migration.name



def test_translates_current_timestamp_assignment_to_text():
    result = translate_migration_sql(
        "UPDATE customer_accounts SET updated_at=CURRENT_TIMESTAMP;",
        "015_activate_existing_beta_accounts.sql",
    )
    assert "updated_at=to_char(timezone('utc', CURRENT_TIMESTAMP)" in result
